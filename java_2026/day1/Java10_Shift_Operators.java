public class Java10_Shift_Operators {
    public static void main(String[] args) {
        //  << >> >>>

        int x=3;
        System.out.println(x << 1);//0011 => 0110=6
        System.out.println(x >> 1);//0011 => 0001=1
        System.out.println(x >>> 1);//0011 => 0110=6
        
    }
    
}
