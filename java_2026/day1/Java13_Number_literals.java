public class Java13_Number_literals {
    public static void main(String[] args) {
        int x=10; // decimal litral
        System.out.println(x);

        int a=0b1010;//binary 
        System.out.println(a);

        int b=012;// octal litrals
        System.out.println(b);

        int c=0xA;//Hexadcimal litrals
        System.out.println(c);

        int value1=140000000;
        System.out.println(value1);

        int value2=1_400_000_000;
        System.out.println(value2);


    }
    
}
